    private void TableGaragemMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TableGaragemMouseClicked
        int linha = TableGaragem.getSelectedRow();

        if (linha == -1) {
            return;
        }

        int codigo = Integer.parseInt(
                TableGaragem.getValueAt(linha, 0).toString()
        );

        txtID.setText(String.format("%05d", codigo));

        txtMarca.setText(
                String.valueOf(TableGaragem.getValueAt(linha, 1))
        );

        txtModelo.setText(
                String.valueOf(TableGaragem.getValueAt(linha, 2))
        );

        int codAno = Integer.parseInt(
                TableGaragem.getValueAt(linha, 3).toString()
        );

        txtAno.setText(String.format("%04d", codAno));
        
        int codCilindrada = Integer.parseInt(
                TableGaragem.getValueAt(linha, 4).toString()
        );

        txtCilindrada.setText(String.format("%04d", codCilindrada));   
    }//GEN-LAST:event_TableGaragemMouseClicked

