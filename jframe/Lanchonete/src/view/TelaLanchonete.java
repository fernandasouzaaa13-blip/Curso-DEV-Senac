    private void carregarTabela() {
        // Carrega os registros do Model e atualiza as linhas da tabela na View.(Método)
        DefaultTableModel modelo = (DefaultTableModel) TableCentral.getModel();//modelo da tabela
        modelo.setRowCount(0); // apaga as linhas atuais
        LanchoneteModel carregar = new LanchoneteModel();
        ArrayList<Object[]> linhas = carregar.listarTodos(); //pede ao model
        for (Object[] linha : linhas) { // adiciona cada linha
            modelo.addRow(linha);
        }
    }
