    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        try {
            String textoValorReal = txtValorReal.getText().replace(",",".");
            double valorReal = Double.parseDouble(textoValorReal);
            
            if (valorReal <= 0) {
                JOptionPane.showMessageDialog(this, "Digite valores maiores que zero!");
                return; // sai do metodo, nao calcula
            }
            
            Conversor conversor = new Conversor(valorReal);
            
            double resultado = conversor.coverterParaDolar();
            
            txtValorDolar.setText(String.format("%.2f", resultado));             
            
        } catch (NumberFormatException erro) {
            // se digitou letras ou deixou vazio, cai aqui em vez de travar
            JOptionPane.showMessageDialog(this, "Digite apenas numeros!");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

