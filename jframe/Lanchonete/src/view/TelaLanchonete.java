    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
        String nome = txtNome.getText().trim();
        String ingredientes = txtIngredientes.getText().trim();
        String tamanho = txtTamanho.getText().trim();

        String textPreco = txtPreco.getText().replace(",", "."); // replace troca a virgula por ponto para por exempro 25,60 ser 25.60
        double preco = Double.parseDouble(textPreco);// convertendo o texto em numero decimal (DOUBLE)

        LanchoneteModel cadastro = new LanchoneteModel();
        cadastro.inserir(nome, ingredientes, tamanho, preco);
        JOptionPane.showMessageDialog(
                null,
                "Cadastro realizado com sucesso!",
                "Sucesso",
                JOptionPane.INFORMATION_MESSAGE
        );
        LimparCampos();
        carregarTabela();
    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (txtID.getText().equals("")) {
            //mostra uma msg na TelaGaragem que foi gravado
            JOptionPane.showMessageDialog(
                    null,
                    "Favor Selecionar um Registro ",
                    "Sucesso",
                    JOptionPane.INFORMATION_MESSAGE
            );
        } else {
            int id = Integer.parseInt(txtID.getText().trim());

            //Criando o Objeto para ter acesso aos métodos CRUD e atributos
            LanchoneteModel excluir = new LanchoneteModel();
            String resposta = excluir.excluir(id);

            //mostra uma msg na TelaGaragem que foi gravado
            JOptionPane.showMessageDialog(
                    null,
                    resposta,
                    "Sucesso",
                    JOptionPane.INFORMATION_MESSAGE
            );

            //Limpar as caixas de Texto
            LimparCampos();

            //Carregando a tabela ao iniciar
            carregarTabela();
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

