    private void carregarTabela() {
        DefaultTableModel modelo = (DefaultTableModel) TableGaragem.getModel();//modelo da tabela
        modelo.setRowCount(0); // apaga as linhas atuais
        GaragemModel garagem = new GaragemModel();
        ArrayList<Object[]> linhas = garagem.listarTodos(); //pede ao model
        for (Object[] linha : linhas) { // adiciona cada linha
            modelo.addRow(linha);
        }

    }

