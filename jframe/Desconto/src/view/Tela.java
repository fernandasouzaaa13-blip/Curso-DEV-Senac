    private void bntAplicarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bntAplicarActionPerformed
        String produto = txtProduto.getText();
        double preco = Double.parseDouble(txtPreco.getText());
        double desconto = Double.parseDouble(txtDesconto.getText());

        Desconto d = new Desconto(produto, preco, desconto);

        double valorDesconto = d.calcularDesconto();
        double precoFinal = d.calcularPrecoFinal();

       txtValorDesconto.setText(String.format("R$ %.2f", valorDesconto));
        txtPrecoFinal.setText(String.format("R$ %.2f", precoFinal));
    }//GEN-LAST:event_bntAplicarActionPerformed

